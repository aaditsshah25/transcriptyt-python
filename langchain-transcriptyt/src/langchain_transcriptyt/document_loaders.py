from __future__ import annotations

from typing import Any, Iterator, Literal, Optional, Sequence, Union

from langchain_core.document_loaders import BaseLoader
from langchain_core.documents import Document
from transcriptyt import TranscriptYT

BATCH_SIZE = 50


class TranscriptYTLoader(BaseLoader):
    """Load YouTube transcripts with the TranscriptYT API.

    Works from cloud servers (requests go through rotating proxies), supports
    150+ languages and translation, and falls back to AI transcription when a
    video has no captions.

    Setup:
        .. code-block:: bash

            pip install -U langchain-transcriptyt
            export TRANSCRIPTYT_API_KEY="ts_live_..."

    Instantiate:
        .. code-block:: python

            from langchain_transcriptyt import TranscriptYTLoader

            loader = TranscriptYTLoader(
                urls=["https://www.youtube.com/watch?v=dQw4w9WgXcQ"],
                # playlist="https://www.youtube.com/@channel",  # or a playlist / channel
                # language="en", translate_to="es",
                # chunk="paragraph", chunk_size=1000,
            )

    Load:
        .. code-block:: python

            docs = loader.load()
            print(docs[0].page_content[:100])
            print(docs[0].metadata)
    """

    def __init__(
        self,
        urls: Union[str, Sequence[str], None] = None,
        *,
        playlist: Optional[str] = None,
        limit: Optional[int] = None,
        language: Optional[str] = None,
        translate_to: Optional[str] = None,
        chunk: Literal["video", "paragraph"] = "video",
        chunk_size: Optional[int] = None,
        mode: Literal["auto", "captions", "ai"] = "auto",
        continue_on_failure: bool = True,
        api_key: Optional[str] = None,
        client: Optional[TranscriptYT] = None,
    ):
        """
        Args:
            urls: YouTube URLs or 11-character video IDs.
            playlist: A playlist or channel URL to load instead (up to 50 videos).
            limit: Max videos to take from `playlist`.
            language: BCP-47 code of the caption track to fetch.
            translate_to: Machine-translate transcripts into this language.
            chunk: "video" for one Document per video, "paragraph" for one per paragraph with start/end times.
            chunk_size: Max characters per paragraph when chunk="paragraph" (50-10000).
            mode: "auto" (captions, AI fallback), "captions" (never AI), or "ai".
            continue_on_failure: Skip videos that fail instead of raising.
            api_key: TranscriptYT key; defaults to the TRANSCRIPTYT_API_KEY env var.
            client: An existing `transcriptyt.TranscriptYT` client.
        """
        if isinstance(urls, str):
            urls = [urls]
        if not urls and not playlist:
            raise ValueError("Provide urls or playlist.")
        self.urls = list(urls or [])
        self.playlist = playlist
        self.limit = limit
        self.chunk = chunk
        self.continue_on_failure = continue_on_failure
        self.options: dict[str, Any] = {
            k: v
            for k, v in {
                "language": language,
                "translate_to": translate_to,
                "mode": mode,
                "paragraphs": chunk == "paragraph" or None,
                "chunkSize": chunk_size,
            }.items()
            if v is not None
        }
        self.client = client or TranscriptYT(api_key=api_key)

    def _batches(self) -> Iterator[dict]:
        if self.playlist:
            yield self.client.transcripts(playlist=self.playlist, limit=self.limit, **self.options)
            return
        for i in range(0, len(self.urls), BATCH_SIZE):
            yield self.client.transcripts(self.urls[i : i + BATCH_SIZE], **self.options)

    def lazy_load(self) -> Iterator[Document]:
        for batch in self._batches():
            for result in batch["results"]:
                if not result["ok"]:
                    if self.continue_on_failure:
                        continue
                    error = result.get("error") or {}
                    raise ValueError(f"{result['url']}: {error.get('code')} {error.get('message')}")
                yield from self._documents(result["transcript"])

    def _documents(self, t: dict) -> Iterator[Document]:
        video_url = f"https://www.youtube.com/watch?v={t['videoId']}"
        base = {
            "source": video_url,
            "video_id": t["videoId"],
            "title": t.get("title"),
            "author": t.get("author"),
            "channel_id": t.get("channelId"),
            "language": t.get("language"),
            "translated": t.get("translated"),
            "auto_generated": t.get("autoGenerated"),
            "duration_seconds": t.get("durationSeconds"),
            "transcript_source": t.get("source"),
        }
        if self.chunk == "video":
            yield Document(page_content=t["text"], metadata=base)
            return
        for seg in t["segments"]:
            start = int(seg["start"])
            yield Document(
                page_content=seg["text"],
                metadata={**base, "source": f"{video_url}&t={start}s", "start": seg["start"], "end": seg["end"]},
            )
